"""Build RESULTS.md from committed receipts and anchors.json. Partial receipts are never shown as results.

    python bench/report.py
For each dataset, the latest non-partial receipt per engine is listed next to the published anchors, with latency scope marked.
"""
from __future__ import annotations

import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
TASKS = {"scifact": "SciFact", "nfcorpus": "NFCorpus", "syntec": "SyntecRetrieval", "alloprof": "AlloprofRetrieval"}


def latest() -> dict:
    out: dict = {}
    for f in sorted((HERE / "receipts").glob("*.json")):
        r = json.loads(f.read_text(encoding="utf-8"))
        if r.get("partial") or r["protocol"] != "v1":
            continue
        out[(r["dataset"]["id"], r["engine"]["id"])] = (f.name, r)
    return out


def main() -> None:
    anchors = json.loads((HERE / "anchors.json").read_text(encoding="utf-8"))
    runs = latest()
    lines = ["# Results", "", "Generated by `bench/report.py` from `bench/receipts/`. Partial receipts are excluded. "
             "Receipts made before the `bench-v1` tag are provisional.", ""]
    for ds, task in TASKS.items():
        rows = [(e, f, r) for (d, e), (f, r) in runs.items() if d == ds]
        if not rows and not any(a["task"] == task for a in anchors["mteb"]):
            continue
        lines += [f"## {ds}", "", "| System | nDCG@10 | Recall@10 | Empty queries | p50 ms | Latency scope | Deterministic |", "|---|---|---|---|---|---|---|"]
        for e, f, r in sorted(rows):
            m = r["metrics"]
            lines.append(f"| `{e}` | {m['ndcg@10']:.3f} | {m['recall@10']:.3f} | {m['queries_empty']}/{m['queries_scored']} | "
                         f"{r['latency_ms']['p50']} | {r['latency_ms']['scope'].split(' (')[0].split(':')[0]} | {r['determinism']['identical_rankings']} |")
        for a in anchors["beir_bm25"]:
            if a["dataset"] == ds:
                lines.append(f"| *published BM25 (BEIR paper)* | {a['ndcg_at_10']:.3f} | | | | | verified_by_fetch={a['verified_by_fetch']} |")
        for a in anchors["mteb"]:
            if a["task"] == task and a["scores_test"]:
                s = a["scores_test"][0]
                lines.append(f"| *published dense, {a['model'].split('__')[1]}* | {s['ndcg_at_10']:.3f} | "
                             f"{(s.get('recall_at_10') or 0):.3f} | | | | MTEB {a['mteb_version']} |")
        lines.append("")
    lme = sorted((HERE / "receipts").glob("*longmemeval_s*.json"))
    full = [json.loads(f.read_text(encoding="utf-8")) for f in lme]
    full = [r for r in full if not r.get("partial") and r["protocol"] == "v1"]
    if full:
        lines += ["## longmemeval_s (retrieval only, session level)", "", '> Earlier run, 12 November 2026: 470 questions (abstention-tagged ones excluded), a fresh process per query and AND lexical matching, with a single embedding model per row (MiniLM-L12 or e5-small). The current figure for the shipped binary is any@5 0.978, all@5 0.908 on all 500 questions, run on 14 November: see [`experiments/LONGMEM-ICM.md`](experiments/LONGMEM-ICM.md). The two runs differ in question set and engine, so they are not directly comparable.', "", "| System | recall_any@5 | recall_any@10 | recall_all@5 | nDCG@10 |", "|---|---|---|---|---|"]
        for r in full:
            m = r["metrics"]
            lines.append(f"| `{r['engine']['id']}` | {m['recall_any@5']:.3f} | {m['recall_any@10']:.3f} | {m['recall_all@5']:.3f} | {m['ndcg@10']:.3f} |")
        lines.append("")
    (HERE / "RESULTS.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
