#!/usr/bin/env python3
"""Third-party notices: every dependency that ships in Footnote's binaries, with its licence.

Reads `cargo metadata` for the engine and for apps/launcher/src-tauri (normal and build dependencies only, all features, so the
list covers every build we ship), and the launcher's production npm packages from its package-lock.json. Writes
THIRD-PARTY-NOTICES.md; `--check` instead fails when the file is out of date or a licence is not on the allowlist below.

Allowlist: licences that allow commercial use and redistribution in a closed product (Footnote Enterprise builds on this
engine). A dependency whose licence offers a choice ("MIT OR LGPL") passes when one option is allowed.
"""
import json
import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "THIRD-PARTY-NOTICES.md"
ALLOWED = {
    "MIT", "Apache-2.0", "BSD-2-Clause", "BSD-3-Clause", "ISC", "Zlib", "zlib-acknowledgement", "0BSD", "Unlicense",
    "CC0-1.0", "BSL-1.0", "Unicode-3.0", "Unicode-DFS-2016", "MPL-2.0", "CDLA-Permissive-2.0", "OFL-1.1",
    "Apache-2.0 WITH LLVM-exception", "blessing", "WTFPL",
}


def allowed(expr):
    """True when the SPDX expression can be satisfied with allowed licences (old `/` means OR)."""
    if not expr:
        return False
    expr = expr.replace("/", " OR ")
    expr = re.sub(r"Apache-2\.0 WITH LLVM-exception", "Apache-2.0", expr)
    # Evaluate as a boolean formula: each licence id becomes True or False.
    tokens = re.findall(r"\(|\)|AND|OR|[A-Za-z0-9.+-]+", expr)
    py = " ".join({"AND": "and", "OR": "or", "(": "(", ")": ")"}.get(t, str(t in ALLOWED)) for t in tokens)
    return bool(eval(py))  # only True/False/and/or/parentheses reach here


def cargo(manifest):
    meta = json.loads(subprocess.run(
        ["cargo", "metadata", "--format-version", "1", "--locked", "--all-features", "--manifest-path", str(manifest)],
        check=True, capture_output=True, text=True, encoding="utf-8").stdout)
    pkgs = {p["id"]: p for p in meta["packages"]}
    ours = set(meta["workspace_members"])
    deps = {n["id"]: n["deps"] for n in meta["resolve"]["nodes"]}
    seen, todo = set(), list(ours)
    while todo:
        for d in deps[todo.pop()]:
            # Shipped: normal or build dependencies (dev-dependencies only build the tests).
            if any(k["kind"] in (None, "build") for k in d["dep_kinds"]) and d["pkg"] not in seen:
                seen.add(d["pkg"])
                todo.append(d["pkg"])
    out = []
    for pid in seen - ours:
        p = pkgs[pid]
        out.append((p["name"], p["version"], p["license"] or "", p.get("repository") or ""))
    return out


def npm(lock):
    data = json.loads(lock.read_text(encoding="utf-8"))
    out = []
    for path, p in data["packages"].items():
        if path and not p.get("dev") and not p.get("optional"):
            name = path.split("node_modules/")[-1]
            out.append((name, p["version"], p.get("license", ""), ""))
    return out


def main():
    rust = sorted(set(cargo(ROOT / "Cargo.toml")) | set(cargo(ROOT / "apps/launcher/src-tauri/Cargo.toml")))
    web = sorted(npm(ROOT / "apps/launcher/package-lock.json"))
    bad = [r for r in rust + web if not allowed(r[2])]
    lines = [
        "# Third-party notices",
        "",
        "Every third-party package compiled into Footnote's engine and launcher, with its licence. Generated by",
        "`python scripts/third_party.py`; CI runs it with `--check`. Licence texts are in each package's source distribution.",
        "",
        f"## Rust crates ({len(rust)})",
        "",
        "| Crate | Version | Licence | Source |",
        "|---|---|---|---|",
        *[f"| {n} | {v} | {lic} | {src} |" for n, v, lic, src in rust],
        "",
        f"## Launcher web packages ({len(web)})",
        "",
        "| Package | Version | Licence |",
        "|---|---|---|",
        *[f"| {n} | {v} | {lic} |" for n, v, lic, _ in web],
        "",
    ]
    text = "\n".join(lines)
    if "--check" in sys.argv:
        stale = not OUT.exists() or OUT.read_text(encoding="utf-8") != text
        for n, v, lic, _ in bad:
            print(f"not allowed: {n} {v} ({lic or 'no licence field'})")
        if stale:
            print("THIRD-PARTY-NOTICES.md is out of date: run python scripts/third_party.py")
        sys.exit(1 if bad or stale else 0)
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"{len(rust)} crates, {len(web)} web packages, {len(bad)} not allowed")
    for n, v, lic, _ in bad:
        print(f"not allowed: {n} {v} ({lic or 'no licence field'})")


if __name__ == "__main__":
    assert allowed("MIT OR Apache-2.0") and allowed("(MIT OR Apache-2.0) AND Unicode-3.0")
    assert allowed("MIT OR Apache-2.0 OR LGPL-2.1-or-later") and not allowed("LGPL-2.1-or-later")
    assert not allowed("GPL-3.0 AND MIT") and allowed("Apache-2.0 WITH LLVM-exception") and not allowed("")
    assert allowed("MIT AND BSD-3-Clause AND blessing AND WTFPL")
    main()
